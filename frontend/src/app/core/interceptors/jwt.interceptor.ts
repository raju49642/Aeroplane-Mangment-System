import { HttpInterceptorFn } from '@angular/common/http';
import { inject } from '@angular/core';
import { AuthService } from '../services/auth.service';

/**
 * Attaches the stored JWT (captured at login) to every outgoing API request as
 * "Authorization: Bearer <token>". Public endpoints (register, login, admin
 * register-request) don't need it, but sending it anyway is harmless since
 * those endpoints don't require authentication.
 */
export const jwtInterceptor: HttpInterceptorFn = (req, next) => {
  const authService = inject(AuthService);
  const token = authService.getToken();

  if (!token || !req.url.includes('/api/')) {
    return next(req);
  }

  const authReq = req.clone({
    setHeaders: { Authorization: `Bearer ${token}` }
  });

  return next(authReq);
};
